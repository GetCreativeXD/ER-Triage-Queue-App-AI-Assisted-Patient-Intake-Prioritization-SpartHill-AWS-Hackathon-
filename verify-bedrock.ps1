# =========================================================================
# verify-bedrock.ps1
# -------------------------------------------------------------------------
# Proves the app genuinely uses Amazon Bedrock. Run this in the SAME
# PowerShell window where your AWS credentials are set (the one where
# `aws sts get-caller-identity` works).
#
# What it does:
#   1. Confirms your AWS identity.
#   2. Starts the Node server (Bedrock LIVE).
#   3. Submits a patient intake over HTTP, which calls Bedrock to summarize.
#   4. Prints the raw description next to the AI summary so you can see the
#      model actually rewrote it (not a raw-text fallback).
#   5. Confirms there were NO "[bedrock] ... failed" lines in the server log.
#
# Usage:   .\verify-bedrock.ps1
# =========================================================================

$ErrorActionPreference = "Stop"
$base = "http://localhost:3001"

Write-Host "=== 1. AWS identity ===" -ForegroundColor Cyan
aws sts get-caller-identity --output json
if ($LASTEXITCODE -ne 0) { Write-Host "No AWS credentials in this window. Set them first." -ForegroundColor Red; exit 1 }

Write-Host "`n=== 2. Starting server ===" -ForegroundColor Cyan
$log = Join-Path $PSScriptRoot "server-verify.log"
if (Test-Path $log) { Remove-Item $log }

# On Windows, npm is npm.cmd (not an .exe), so resolve its full path and launch
# it via cmd.exe. Using bare "npm" with Start-Process fails to find the file.
$npmCmd = (Get-Command npm.cmd -ErrorAction SilentlyContinue)?.Source
if (-not $npmCmd) { $npmCmd = (Get-Command npm -ErrorAction SilentlyContinue)?.Source }
if (-not $npmCmd) { Write-Host "npm not found on PATH. Open a new terminal after installing Node." -ForegroundColor Red; exit 1 }

$server = Start-Process -FilePath "cmd.exe" -ArgumentList "/c", "`"$npmCmd`" start" -NoNewWindow -PassThru `
  -RedirectStandardOutput $log -RedirectStandardError "$log.err" -WorkingDirectory $PSScriptRoot

try {
  # Wait for the server to be ready.
  $ready = $false
  for ($i = 0; $i -lt 20; $i++) {
    Start-Sleep -Milliseconds 500
    try { Invoke-RestMethod -Uri "$base/api/health" -TimeoutSec 2 | Out-Null; $ready = $true; break } catch {}
  }
  if (-not $ready) { throw "Server did not become ready. Check $log" }

  $health = Invoke-RestMethod -Uri "$base/api/health"
  Write-Host "Health:" -ForegroundColor Green
  $health | ConvertTo-Json -Depth 5

  Write-Host "`n=== 3. Submitting intake (triggers Bedrock) ===" -ForegroundColor Cyan
  $desc = "I have had crushing chest pain radiating to my left arm for about an hour, with sweating and shortness of breath. It started while I was resting."

  $session = Invoke-RestMethod -Uri "$base/api/sessions" -Method Post -ContentType "application/json" `
    -Body (@{ sessionCode = "ER-VERIFY-1"; language = "en" } | ConvertTo-Json)

  $body = @{
    answers = @(@{ questionId = "description"; answer = $desc; inputMethod = "typed" })
    signals = @{ severity = 8; trend = "worsening"; warningSigns = @("severe-chest-discomfort"); immediateHelp = $false }
  } | ConvertTo-Json -Depth 6

  $updated = Invoke-RestMethod -Uri "$base/api/sessions/$($session.id)/intake" -Method Post -ContentType "application/json" -Body $body

  Write-Host "`n--- Deterministic priority (from queueRules, NOT AI) ---" -ForegroundColor Yellow
  Write-Host "$($updated.currentPriority) :: $($updated.priorityReason)"

  Write-Host "`n--- Raw patient description (preserved) ---" -ForegroundColor Yellow
  Write-Host $desc

  Write-Host "`n--- aiSummary (returned by Amazon Bedrock) ---" -ForegroundColor Yellow
  Write-Host $updated.aiSummary

  Write-Host "`n=== 4. Verdict ===" -ForegroundColor Cyan
  $logText = (Get-Content $log -Raw) + (Get-Content "$log.err" -Raw -ErrorAction SilentlyContinue)
  if ($logText -match "\[bedrock\].*failed") {
    Write-Host "FAIL: Bedrock call failed and fell back to raw text. See log:" -ForegroundColor Red
    Write-Host $logText
  } elseif ($updated.aiSummary -eq $desc) {
    Write-Host "WARNING: aiSummary equals the raw text. Bedrock may not have transformed it." -ForegroundColor Red
  } else {
    Write-Host "PASS: aiSummary differs from the raw text and no Bedrock errors were logged." -ForegroundColor Green
    Write-Host "      => The summary was genuinely generated by Amazon Bedrock (Claude)." -ForegroundColor Green
  }
}
finally {
  Write-Host "`n=== Stopping server ===" -ForegroundColor Cyan
  # Stop the launcher and any node process serving on our port.
  if ($server -and -not $server.HasExited) { Stop-Process -Id $server.Id -Force -ErrorAction SilentlyContinue }
  Get-CimInstance Win32_Process -Filter "Name='node.exe'" -ErrorAction SilentlyContinue |
    Where-Object { $_.CommandLine -like "*backend/server.js*" -or $_.CommandLine -like "*backend\server.js*" } |
    ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }
  # Clean up temporary log files.
  Remove-Item $log, "$log.err" -ErrorAction SilentlyContinue
}
